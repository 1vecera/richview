use richview_publish_server::{ledger::*, migrate::*, wire::migrate_json};
use serde_json::json;
use std::collections::BTreeMap;

fn old_state() -> serde_json::Value {
    json!({
        "generation": 5, "active": "a".repeat(64), "paused": false,
        "hidden": {"gone": {"revision": "r", "actor": "email:e@x", "reason": "legal", "at": "2026-10-20T10:00:00Z", "reconciliation": "pending"}},
        "policies": {"story": {"id": "story", "section": "research", "state": "published", "audience": "public"}},
        "roles": {"email:ed@x": {"name": "editor", "sections": ["research"], "audiences": ["members"], "github_login": "ed"}},
        "edits": {"12": {"number": 12, "url": "u", "head": "h", "branch": "b", "actor": "github:someone", "imported": true, "state": "pending review"}},
        "approvals": {"h": {"actor": "email:boss@x", "pull": 12, "at": "2026-10-21T00:00:00Z"}},
        "authorized": {
            "c1": {"actor": "email:boss@x", "pull": 3, "head": "h0", "base": "b0"},
            "bootstrap-commit": {"actor": "bootstrap", "head": "bootstrap-commit"}
        },
        "builds": {"c1": {"state": "live", "release": "a".repeat(64)}},
        "auditSequence": 41, "accessRevision": 9
    })
}

#[test]
fn a_pr70_ledger_moves_over_with_every_fact_kept() {
    let release = "a".repeat(64);
    let activated = BTreeMap::from([(release.clone(), json!({"commit": "c".repeat(40)}))]);
    let runtimes = BTreeMap::from([("rt".to_string(), json!({"richview_runtime.js": "h1"}))]);
    let old = old_state();
    let unchanged = old.clone();
    let state = from_pr70(&old, &activated, &runtimes).unwrap();
    assert_eq!((state.generation, state.revision), (5, 0));
    assert_eq!(state.active.as_deref(), Some(release.as_str()));
    assert_eq!((state.audit_sequence, state.access_revision), (41, 9));
    assert!(state.hidden.contains_key("gone"));
    assert_eq!(state.hidden["gone"].reason, "legal");
    assert_eq!(state.policies["story"].audience, "public");
    assert!(!state.policies["story"].deleted);
    assert_eq!(
        state.roles["email:ed@x"].github_login.as_deref(),
        Some("ed")
    );
    assert_eq!(state.edits[&12].state, EditState::PendingReview);
    assert!(state.approvals.contains_key("h"));
    assert_eq!(state.authorized["c1"].base.as_deref(), Some("b0"));
    let bootstrap = &state.authorized["bootstrap-commit"];
    assert_eq!(bootstrap.pull, 0);
    assert_eq!(bootstrap.actor, "bootstrap");
    assert_eq!(bootstrap.head.as_deref(), Some("bootstrap-commit"));
    assert_eq!(old, unchanged);
    assert_eq!(state.builds["c1"].state, BuildState::Live);
    assert_eq!(state.activated[&release], "c".repeat(40));
    assert_eq!(state.runtimes["rt"]["richview_runtime.js"], "h1");
    // Nothing that was public becomes private.
    assert!(state.private.is_empty());
}
#[test]
fn migration_is_deterministic_and_recognises_only_old_records() {
    let a = from_pr70(&old_state(), &BTreeMap::new(), &BTreeMap::new()).unwrap();
    let b = from_pr70(&old_state(), &BTreeMap::new(), &BTreeMap::new()).unwrap();
    assert_eq!(
        serde_json::to_string(&a).unwrap(),
        serde_json::to_string(&b).unwrap()
    );
    assert!(is_pr70(&old_state()));
    assert!(!is_pr70(&serde_json::to_value(&a).unwrap()));
}
#[test]
fn a_ledger_that_does_not_fit_is_refused_not_guessed() {
    assert!(from_pr70(&json!(7), &BTreeMap::new(), &BTreeMap::new()).is_err());
    let bad = json!({"generation": "five"});
    assert!(from_pr70(&bad, &BTreeMap::new(), &BTreeMap::new()).is_err());
    let out: serde_json::Value =
        serde_json::from_str(&migrate_json(r#"{"state":{"generation":"x"}}"#)).unwrap();
    assert_eq!(out["kind"], "invalid");
    for approval in [
        json!({"actor": "email:boss@x", "head": "bootstrap-commit"}),
        json!({"actor": "bootstrap", "head": "other"}),
        json!({"actor": "bootstrap", "head": "bootstrap-commit", "extra": true}),
        json!({"actor": "bootstrap", "head": "bootstrap-commit", "pull": null}),
    ] {
        let mut old = old_state();
        old["authorized"]["bootstrap-commit"] = approval;
        assert!(from_pr70(&old, &BTreeMap::new(), &BTreeMap::new()).is_err());
    }
}

#[test]
fn the_pinned_pr70_producers_ledger_keeps_its_access_and_publication_facts() {
    // Generated by b4b45a06's unmodified Worker: five activations, staging, roles, hide,
    // sync, approval and failed/building APIs, with fixture-only Git replies and a fixed clock.
    let input: serde_json::Value =
        serde_json::from_str(include_str!("fixtures/pr70-ledger.json")).unwrap();
    let out: serde_json::Value = serde_json::from_str(&migrate_json(&input.to_string())).unwrap();
    assert_eq!(out["kind"], "migrated");
    let state: State = serde_json::from_value(out["state"].clone()).unwrap();
    assert_eq!((state.generation, state.revision), (5, 0));
    assert_eq!(state.audit_sequence, 17);
    assert_eq!(state.access_revision, 0); // The pinned old producer did not write this counter.
    assert_eq!(state.authorized[&"1".repeat(40)].pull, 0);
    assert_eq!(state.authorized[&"2".repeat(40)].pull, 2);
    assert_eq!(
        state.authorized[&"2".repeat(40)].base.as_deref(),
        Some("1".repeat(40).as_str())
    );
    assert_eq!(state.hidden["retired"].reconciliation, "pending");
    assert_eq!(state.hidden["retired"].reason, "Fixture urgent withdrawal");
    assert!(state.policies["retired"].deleted);
    assert_eq!(
        state.roles["email:reader@example.test"].audiences,
        ["members"]
    );
    assert_eq!(state.edits[&50].state, EditState::Approved);
    assert_eq!(state.approvals.values().next().unwrap().pull, 50);
    assert_eq!(state.builds[&"6".repeat(40)].state, BuildState::Building);
    assert_eq!(state.builds[&"7".repeat(40)].state, BuildState::Failed);
    assert!(
        state
            .builds
            .values()
            .any(|build| build.state == BuildState::Built)
    );
    assert_eq!(state.activated.len(), 5);
    assert_eq!(
        state.activated[state.active.as_ref().unwrap()],
        "5".repeat(40)
    );
    assert!(
        state
            .runtimes
            .values()
            .any(|files| files.contains_key("richview_web.js"))
    );
    assert!(state.private.is_empty());
    assert!(
        input["state"]["authorized"]["1".repeat(40)]
            .get("pull")
            .is_none()
    );
}
